#!/usr/bin/env python
"""Train remaining cross-validation folds for Biohub Cell Tracking.

This script trains folds 1, 2, 3, and 4 (or any subset specified) using the
stratified, leak-free 5-fold cross-validation splits generated by create_dataset_splits.py.

Usage:
    python train_remaining_folds.py --folds 1 2 3 4 --epochs 50 --batch-size 8
"""

import argparse
import os
import subprocess
import sys
from pathlib import Path

# Paths
PROJECT_ROOT = Path(__file__).resolve().parent
REPO_DIR = PROJECT_ROOT / "repo"
SCRIPTS_DIR = REPO_DIR / "scripts"
SRC_DIR = REPO_DIR / "src"
DEFAULT_DATA_DIR = Path(r"D:\Downloads_2\biohub-cell-tracking-during-development\train")
DEFAULT_SPLITS = PROJECT_ROOT / "dataset_splits.json"
DEFAULT_WEIGHTS_DIR = REPO_DIR / "weights" / "unet_transformer"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Train remaining CV folds for UNet + Transformer.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "--folds",
        type=int,
        nargs="+",
        default=[1, 2, 3, 4],
        help="Fold indices to train (e.g. 1 2 3 4).",
    )
    parser.add_argument(
        "--data-dir",
        type=str,
        default=str(DEFAULT_DATA_DIR),
        help="Path to training datasets (.zarr and .geff).",
    )
    parser.add_argument(
        "--splits",
        type=str,
        default=str(DEFAULT_SPLITS),
        help="Path to dataset_splits.json.",
    )
    parser.add_argument(
        "--epochs",
        type=int,
        default=50,
        help="Number of training epochs per fold.",
    )
    parser.add_argument(
        "--batch-size",
        type=int,
        default=8,
        help="Batch size (number of window pairs per step).",
    )
    parser.add_argument(
        "--num-workers",
        type=int,
        default=0 if os.name == "nt" else 4,
        help="DataLoader worker processes (0 recommended on Windows to avoid spawn overhead).",
    )
    parser.add_argument(
        "--lr",
        type=float,
        default=1e-4,
        help="Learning rate for AdamW.",
    )
    parser.add_argument(
        "--pool-kernel-um",
        type=float,
        default=5.0,
        help="Suppression distance in microns.",
    )
    parser.add_argument(
        "--det-loss-weight",
        type=float,
        default=1.0,
        help="Detection loss weight.",
    )
    parser.add_argument(
        "--det-neg-weight",
        type=float,
        default=0.01,
        help="Negative voxel weight for detection loss.",
    )
    parser.add_argument(
        "--pretrained-weights",
        type=str,
        default=str(DEFAULT_WEIGHTS_DIR / "split_0" / "edge_predictor_best.pth"),
        help="Path to pretrained weights for warm start.",
    )
    parser.add_argument(
        "--freeze-unet",
        action="store_true",
        default=False,
        help="Freeze UNet backbone and fine-tune mitosis head and transformer only.",
    )
    parser.add_argument(
        "--mitosis-loss-weight",
        type=float,
        default=1.0,
        help="Weight for mitosis classification loss.",
    )
    parser.add_argument(
        "--max-iters",
        type=int,
        default=None,
        help="Max training iterations per epoch.",
    )
    parser.add_argument(
        "--single-gpu",
        action="store_true",
        default=True,
        help="Train on single GPU (cuda:0).",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()

    data_dir = Path(args.data_dir)
    splits_path = Path(args.splits)
    if not data_dir.exists():
        print(f"ERROR: data directory does not exist: {data_dir}", file=sys.stderr)
        sys.exit(1)
    if not splits_path.exists():
        print(f"ERROR: splits file does not exist: {splits_path}", file=sys.stderr)
        sys.exit(1)

    print("=" * 70)
    print("BIOHUB CELL TRACKING -- CV FOLD TRAINING RUNNER")
    print(f"Folds to train: {args.folds}")
    print(f"Data directory: {data_dir}")
    print(f"Splits file:    {splits_path}")
    print(f"Epochs/fold:    {args.epochs}")
    print(f"Batch size:     {args.batch_size}")
    print(f"Num workers:    {args.num_workers}")
    print(f"Learning rate:  {args.lr}")
    print("=" * 70)

    # Set up environment for subprocess execution
    env = os.environ.copy()
    pythonpath = [str(SRC_DIR), str(SCRIPTS_DIR)]
    if "PYTHONPATH" in env:
        pythonpath.append(env["PYTHONPATH"])
    env["PYTHONPATH"] = os.pathsep.join(pythonpath)

    train_script = SCRIPTS_DIR / "train_unet_transformer.py"
    if not train_script.exists():
        print(f"ERROR: train script not found at {train_script}", file=sys.stderr)
        sys.exit(1)

    for fold in args.folds:
        print(f"\n>>> Starting training for FOLD {fold} of {args.folds}...")
        fold_out = DEFAULT_WEIGHTS_DIR / f"split_{fold}"
        ckpt_path = fold_out / "edge_predictor_best.pth"
        if ckpt_path.exists():
            print(f"Notice: Checkpoint already exists at {ckpt_path}.")
            print(f"Training fold {fold} will resume or update this checkpoint.")

        cmd = [
            sys.executable,
            str(train_script),
            "--data-dir", str(data_dir),
            "--splits", str(splits_path),
            "--split", str(fold),
            "--epochs", str(args.epochs),
            "--batch-size", str(args.batch_size),
            "--num-workers", str(args.num_workers),
            "--lr", str(args.lr),
            "--pool-kernel-um", str(args.pool_kernel_um),
            "--det-loss-weight", str(args.det_loss_weight),
            "--det-neg-weight", str(args.det_neg_weight),
            "--mitosis-loss-weight", str(args.mitosis_loss_weight),
        ]
        if args.pretrained_weights and Path(args.pretrained_weights).exists():
            cmd.extend(["--pretrained-weights", str(args.pretrained_weights)])
        if args.freeze_unet:
            cmd.append("--freeze-unet")
        if args.max_iters is not None:
            cmd.extend(["--max-iters", str(args.max_iters)])
        if args.single_gpu:
            cmd.append("--single-gpu")

        print(f"Running command: {' '.join(cmd)}")
        result = subprocess.run(cmd, env=env, cwd=str(PROJECT_ROOT))
        if result.returncode != 0:
            print(f"\nERROR: Training fold {fold} failed with code {result.returncode}!", file=sys.stderr)
            sys.exit(result.returncode)

        if ckpt_path.exists():
            print(f">>> Fold {fold} training completed successfully! Checkpoint: {ckpt_path}")
        else:
            print(f">>> WARNING: Training finished but checkpoint not found at {ckpt_path}")

    print("\n" + "=" * 70)
    print("ALL REQUESTED FOLDS HAVE FINISHED TRAINING!")
    print("Trained checkpoints are ready in repo/weights/unet_transformer/split_*")
    print("=" * 70)


if __name__ == "__main__":
    main()
